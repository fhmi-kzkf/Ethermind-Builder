import { GateIssue, SpecDefinition } from '../../types';
import llmRouter, { BudgetExceededError } from '../llm/router';
import { WorkspaceFileManager } from '../sandbox/fileManager';
import { fileFormatInstructions, parseFileBlocks } from './fileBlocks';
import { isFrontendFile, isOwnedPath, listOwnedFiles } from './ownership';

const MAX_PROTECTED_EXCERPT = 6000;
const CONCURRENCY = 2;
/** Findings that name no file are spread over at most this many files, so one vague note cannot trigger a rewrite of everything. */
const MAX_FILES_FOR_GENERAL_NOTES = 4;

/** A few numbered lines around the reported line, so the model sees what the tool is complaining about. */
async function codeAround(fm: WorkspaceFileManager, file: string | undefined, line: number | undefined): Promise<string> {
  if (!file || !line || !fm.fileExists(file)) return '';
  const lines = (await fm.readFile(file)).split('\n');
  const from = Math.max(0, line - 5);
  const excerpt = lines.slice(from, line + 3).map((text, i) => `      ${String(from + i + 1).padStart(4)}| ${text}`);
  return `\n   code around line ${line}:\n${excerpt.join('\n')}`;
}

async function describeIssues(issues: GateIssue[], fm: WorkspaceFileManager): Promise<string> {
  const parts: string[] = [];
  for (const [index, issue] of issues.entries()) {
    const where = issue.file ? `${issue.file}${issue.line ? `:${issue.line}` : ''} ` : '';
    const hint = issue.fixRecommendation ? `\n   fix hint: ${issue.fixRecommendation}` : '';
    parts.push(`${index + 1}. [${issue.severity}] ${where}${issue.message}${hint}${await codeAround(fm, issue.file, issue.line)}`);
  }
  return parts.join('\n');
}

export class RemediationAgent {
  /**
   * Repairs the hand-written files so the failing gates pass, one file per model call. A reply holds a single
   * file, so it cannot be cut off by the output limit the way "rewrite every page at once" was.
   * Platform-generated files are read-only context: a failure that originates there has to be fixed in the
   * hand-written code that feeds it. Returns the paths that actually changed.
   * Throws only when every call failed and nothing changed, so the caller can report why.
   */
  public static async fix(
    spec: SpecDefinition,
    fm: WorkspaceFileManager,
    issues: GateIssue[],
    projectId: string,
    jobId: string,
    overrideModel?: string
  ): Promise<string[]> {
    const owned = await listOwnedFiles(spec, fm);

    const perFile = new Map<string, GateIssue[]>();
    const general: GateIssue[] = [];
    for (const issue of issues) {
      if (issue.file && owned.includes(issue.file)) perFile.set(issue.file, [...(perFile.get(issue.file) ?? []), issue]);
      else general.push(issue);
    }

    // Notes that name no hand-written file go to the files of the side they concern.
    if (general.length > 0) {
      const frontend = general.some((i) => i.file && isFrontendFile(i.file));
      const candidates = owned.filter((p) => isFrontendFile(p) === frontend && !perFile.has(p) && !p.startsWith('tests/'));
      for (const file of candidates.slice(0, MAX_FILES_FOR_GENERAL_NOTES)) perFile.set(file, []);
    }

    const changed: string[] = [];
    const failures: unknown[] = [];
    const queue = Array.from(perFile.entries());
    let budgetError: BudgetExceededError | null = null;

    // Two files at a time: files are independent, and one at a time made four pages take seven minutes.
    const worker = async () => {
      for (let next = queue.shift(); next && !budgetError; next = queue.shift()) {
        const [file, fileIssues] = next;
        try {
          if (await this.repairFile(spec, fm, file, fileIssues, general, projectId, jobId, overrideModel)) changed.push(file);
        } catch (error) {
          if (error instanceof BudgetExceededError) budgetError = error;
          else {
            console.warn(`[RemediationAgent] Could not repair ${file}: ${(error as Error).message}`);
            failures.push(error);
          }
        }
      }
    };
    await Promise.all(Array.from({ length: Math.min(CONCURRENCY, queue.length) }, worker));
    if (budgetError) throw budgetError;

    if (changed.length === 0 && failures.length > 0) throw failures[0];
    return changed;
  }

  private static async repairFile(
    spec: SpecDefinition,
    fm: WorkspaceFileManager,
    file: string,
    fileIssues: GateIssue[],
    general: GateIssue[],
    projectId: string,
    jobId: string,
    overrideModel?: string
  ): Promise<boolean> {
    const current = await fm.readFile(file);

    const readOnly: string[] = [];
    for (const issue of [...fileIssues, ...general]) {
      if (issue.file && !isOwnedPath(spec, issue.file) && fm.fileExists(issue.file)) {
        const text = await fm.readFile(issue.file);
        readOnly.push(`--- ${issue.file} (generated by the platform, read-only)\n${text.slice(0, MAX_PROTECTED_EXCERPT)}`);
      }
    }

    // A seed or route that breaks on the database needs the real schema (required fields, enum values) in front of it.
    if (fm.fileExists('prisma/schema.prisma') && [...fileIssues, ...general].some((i) => /prisma|seed|Argument `/i.test(i.message)) && !readOnly.some((r) => r.includes('prisma/schema.prisma'))) {
      readOnly.push(`--- prisma/schema.prisma (generated by the platform, read-only)\n${(await fm.readFile('prisma/schema.prisma')).slice(0, MAX_PROTECTED_EXCERPT)}`);
    }

    const isTest = file.startsWith('tests/');
    const systemPrompt = `You repair ONE file of a business web app so that its automated quality gates pass. You are given the exact failures (lint errors, failing tests with their messages, review findings) and the current content of that file.

Rules:
- Return the COMPLETE new content of this one file and nothing else. Do not shorten it, and do not touch other files.
- Fix every finding that concerns this file. Findings listed as "general" may or may not concern it: apply them only where they clearly do.
- Platform-generated files are read-only context: when a generated test fails, the bug is in the code it exercises.
- ${isTest ? 'When this test contradicts the documented behaviour of the app, fix the test; never delete a test or weaken an assertion just to make it pass.' : 'Keep the response contract and the business rules intact. State that must survive between renders lives outside render(), not inside it.'}
- Start the file with its own imports and import only what it uses.

${fileFormatInstructions(file)}`;

    const userPrompt = `TASK: remediation file=${file}
App: ${spec.title}

Findings for this file:
${fileIssues.length > 0 ? await describeIssues(fileIssues, fm) : '(none specific; see the general findings)'}
${general.length > 0 ? `\nGeneral findings (not tied to a hand-written file):\n${await describeIssues(general, fm)}\n` : ''}
${readOnly.length ? `Read-only context:\n${readOnly.join('\n\n')}\n\n` : ''}Current content of ${file}:
${current}`;

    const response = await llmRouter.completeStructured({
      role: isFrontendFile(file) ? 'frontend' : 'backend',
      systemPrompt,
      userPrompt,
      projectId,
      jobId,
      overrideModel,
      parser: parseFileBlocks,
    });

    // Only a block for exactly this file is applied. A reply labelled with another path is never written over it.
    const reply = response.data.files.find((f) => f.path.replace(/\\/g, '/').replace(/^\.?\//, '') === file);
    if (!reply) return false;

    const next = reply.content.endsWith('\n') ? reply.content : `${reply.content}\n`;
    if (next === current) return false;
    await fm.writeFile(file, next);
    return true;
  }
}
